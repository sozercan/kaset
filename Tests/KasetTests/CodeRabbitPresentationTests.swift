import AppKit
import Testing
@testable import Kaset

@MainActor
struct CodeRabbitPresentationTests {
    @Test("Pin movement skips shortcuts hidden by library deduplication")
    func moveVisiblePins() {
        let manager = SidebarPinnedItemsManager(skipLoad: true)
        let first = SidebarPinnedItem.from(TestFixtures.makePlaylist(id: "first"))
        let hidden = SidebarPinnedItem.from(TestFixtures.makePlaylist(id: "hidden"))
        let last = SidebarPinnedItem.from(TestFixtures.makePlaylist(id: "last"))
        manager.reset(with: [first, hidden, last])
        let visible: Set<String> = [first.contentId, last.contentId]
        manager.moveUp(contentId: last.contentId, visibleContentIds: visible)
        #expect(manager.items == [last, hidden, first])
        manager.moveDown(contentId: last.contentId, visibleContentIds: visible)
        #expect(manager.items == [first, hidden, last])
    }

    @Test("Library duplicates hide a pin without deleting external shortcuts")
    func visiblePinsPreserveSavedItems() {
        let manager = SidebarPinnedItemsManager(skipLoad: true)
        let external = SidebarPinnedItem.from(TestFixtures.makePlaylist(id: "PL-external"))
        let saved = SidebarPinnedItem.from(TestFixtures.makePlaylist(id: "VLPL-saved"))
        let album = SidebarPinnedItem.from(TestFixtures.makeAlbum(id: "album"))
        manager.reset(with: [external, saved, album])

        #expect(manager.visibleItems(libraryPlaylistIDs: ["PL-saved"]).map(\.id) == [external.id, album.id])
        #expect(manager.items == [external, saved, album])
        #expect(manager.visibleItems(libraryPlaylistIDs: []).count == 3)
    }

    @Test("Saved editorial playlists remain visible alongside ordinary user playlists")
    func savedEditorialPlaylists() {
        #expect(!LibraryContentIdentity.isAutoGeneratedPlaylist("RDCLAK5uy-editorial"))
        #expect(!LibraryContentIdentity.isAutoGeneratedPlaylist("VLRDCLAK5uy-editorial"))
        #expect(LibraryContentIdentity.isAutoGeneratedPlaylist("RDEM-generated"))
    }

    @Test("Large thumbnails upgrade the path while discarding only size-specific parameters")
    func queriedThumbnailUpgrade() throws {
        let source = try #require(URL(string: "https://i.ytimg.com/vi/example/hqdefault.jpg?sqp=small&rs=size-signature&other=kept"))
        let result = try #require(source.largeThumbnailURL)
        #expect(result.path == "/vi/example/maxresdefault.jpg")
        #expect(URLComponents(url: result, resolvingAgainstBaseURL: false)?.queryItems == [URLQueryItem(name: "other", value: "kept")])
    }

    @Test("Queue column follows narrow and wide panel widths", arguments: [CGFloat(300), 400, 560])
    func queueColumnTracksWidth(width: CGFloat) throws {
        let controller = QueueListControllerRepresentable.QueueListViewController()
        controller.loadView()
        let table = try #require(controller.tableView)
        let scroll = try #require(controller.view as? NSScrollView)
        scroll.setFrameSize(NSSize(width: width, height: 300))
        scroll.tile()
        table.setFrameSize(NSSize(width: scroll.contentSize.width, height: 300))
        table.sizeLastColumnToFit()
        let column = try #require(table.tableColumns.first)
        #expect(scroll.contentSize.width >= width - 20)
        // AppKit's automatic/inset table style reserves up to 16pt per edge.
        #expect(column.width <= scroll.contentSize.width)
        #expect(column.width >= scroll.contentSize.width - 32)
    }
}
